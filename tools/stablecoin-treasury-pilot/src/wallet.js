import { getAddress } from 'ethers/address'
import { computeAddress } from 'ethers/transaction'
import { hexlify } from 'ethers/utils'
import { decryptKeystoreJson, encryptKeystoreJson } from 'ethers/wallet'

export const maximumBackupBytes = 8 * 1024
const scrypt = { N: 2 ** 17, r: 8, p: 1 }

export async function createBaseBackup(password) {
  if (password.length < 14 || password.length > 128) {
    throw new Error('Invalid password length')
  }
  const privateKey = globalThis.crypto.getRandomValues(new Uint8Array(32))
  try {
    const keyHex = hexlify(privateKey)
    const address = getAddress(computeAddress(keyHex))
    const backup = await encryptKeystoreJson({ address, privateKey: keyHex }, password, { scrypt })
    return { address, backup }
  } finally {
    privateKey.fill(0)
  }
}

export async function restoreBaseAddress(backup, password) {
  if (new TextEncoder().encode(backup).byteLength > maximumBackupBytes || password.length > 128) {
    throw new Error('Invalid backup or password')
  }

  const document = JSON.parse(backup)
  const encrypted = document?.Crypto ?? document?.crypto
  const params = encrypted?.kdfparams
  // Only accept the profile generated by this app, so file parameters cannot
  // request unbounded work or trigger mnemonic recovery or a weaker KDF.
  if (document?.version !== 3 || !/^[0-9a-f]{40}$/i.test(document.address) ||
      Object.keys(document).some(key => !['address', 'id', 'version', 'Crypto', 'crypto'].includes(key)) ||
      ('Crypto' in document && 'crypto' in document) ||
      encrypted?.cipher !== 'aes-128-ctr' || encrypted.kdf !== 'scrypt' ||
      !/^[0-9a-f]{64}$/i.test(encrypted.ciphertext) ||
      !/^[0-9a-f]{64}$/i.test(encrypted.mac) ||
      !/^[0-9a-f]{32}$/i.test(encrypted.cipherparams?.iv) ||
      !/^[0-9a-f]{64}$/i.test(params?.salt) ||
      params.n !== scrypt.N || params.r !== scrypt.r || params.p !== scrypt.p || params.dklen !== 32) {
    throw new Error('Unsupported backup format')
  }
  const expected = getAddress(`0x${document.address.toLowerCase()}`)
  const account = await decryptKeystoreJson(backup, password)
  const recovered = getAddress(computeAddress(account.privateKey))
  if (recovered !== expected) {
    throw new Error('Backup does not match its address')
  }
  return recovered
}
